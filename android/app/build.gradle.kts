import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
}

// Release signing: CI writes the keystore from repo secrets (ANDROID_KEYSTORE_B64 / ANDROID_KEYSTORE_PASSWORD).
// Locally: android/keystore.properties (gitignored) with storeFile/storePassword/keyAlias/keyPassword.
val ks = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
    System.getenv("ANDROID_KEYSTORE_FILE")?.let { setProperty("storeFile", it) }
    System.getenv("ANDROID_KEYSTORE_PASSWORD")?.let { setProperty("storePassword", it); setProperty("keyPassword", it) }
    if (getProperty("keyAlias") == null) setProperty("keyAlias", "jellyshell")
}
val hasKs = ks.getProperty("storeFile")?.let { file(it).exists() } == true

// Build-time configuration: gradle property (-PNAME=value) or environment variable, blank = unset.
fun cfg(name: String): String? =
    (project.findProperty(name) as String?)?.trim()?.takeIf { it.isNotEmpty() } ?: System.getenv(name)?.trim()?.takeIf { it.isNotEmpty() }

// applicationId base; the flavors append .tv / .mobile. Forks keep the default. An existing install only updates
// in place when this (and the signing key) stays the same as the build it was installed from.
val appIdBase = cfg("JELLYSHELL_APP_ID") ?: "app.jellyshell"
require(Regex("^[a-zA-Z][a-zA-Z0-9_]*(\\.[a-zA-Z][a-zA-Z0-9_]*)+$").matches(appIdBase)) { "JELLYSHELL_APP_ID '$appIdBase' is not a valid package name" }
// Page-server URL the app opens until the user sets one. Empty = ask on first launch.
val defaultUrl = cfg("JELLYSHELL_DEFAULT_URL") ?: ""
require(defaultUrl.isEmpty() || Regex("^https?://[^\\s\"\\\\]+$").matches(defaultUrl)) { "JELLYSHELL_DEFAULT_URL must be an http(s) URL" }

android {
    namespace = "app.jellyshell"
    compileSdk = 35

    defaultConfig {
        applicationId = appIdBase
        buildConfigField("String", "DEFAULT_URL", "\"$defaultUrl\"")
        minSdk = 24
        targetSdk = 35
        // CI run number -> monotonically increasing versionCode, so every build installs over the previous one.
        // VERSION_OFFSET (optional repo variable) keeps versions above existing installs after a repo move.
        val run = (System.getenv("GITHUB_RUN_NUMBER") ?: "1").toInt() + (System.getenv("VERSION_OFFSET")?.toIntOrNull() ?: 0)
        versionCode = run
        versionName = "1.0.$run"
    }

    buildFeatures { buildConfig = true }

    // tv = Android TV / Google TV (leanback, landscape, D-pad). mobile = phones/tablets (touch UI, rotation).
    // Separate applicationIds (<base>.tv / <base>.mobile) so both can be installed; same signing key.
    flavorDimensions += "device"
    productFlavors {
        create("tv") {
            dimension = "device"
            applicationIdSuffix = ".tv"
            buildConfigField("String", "UA_TAG", "\"JellyShellTV\"")
        }
        create("mobile") {
            dimension = "device"
            applicationIdSuffix = ".mobile"
            buildConfigField("String", "UA_TAG", "\"JellyShellMobile\"")
        }
    }

    signingConfigs {
        if (hasKs) create("release") {
            storeFile = file(ks.getProperty("storeFile"))
            storePassword = ks.getProperty("storePassword")
            keyAlias = ks.getProperty("keyAlias")
            keyPassword = ks.getProperty("keyPassword")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = if (hasKs) signingConfigs.getByName("release") else signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
}

// Phone launcher shortcut (long-press the icon -> "Server address"). A static shortcut's <intent targetPackage> must be the
// literal applicationId: ShortcutManager does not resolve @string references there (it stored "@2130903041" as the
// package) and manifest placeholders don't apply to res/xml. So res/xml/shortcuts.xml is generated per variant.
abstract class ShortcutsXml : DefaultTask() {
    @get:Input abstract val appId: Property<String>
    @get:OutputDirectory abstract val outDir: DirectoryProperty

    @TaskAction fun write() {
        val f = outDir.file("xml/shortcuts.xml").get().asFile
        f.parentFile.mkdirs()
        f.writeText(
            """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/build.gradle.kts (ShortcutsXml) for applicationId ${appId.get()}. -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
    <shortcut android:shortcutId="server" android:enabled="true" android:icon="@mipmap/ic_launcher"
        android:shortcutShortLabel="@string/shortcut_server">
        <intent android:action="app.jellyshell.SETTINGS"
            android:targetPackage="${appId.get()}"
            android:targetClass="app.jellyshell.MainActivity" />
    </shortcut>
</shortcuts>
"""
        )
    }
}

androidComponents {
    onVariants(selector().withFlavor("device" to "mobile")) { v ->
        val t = tasks.register<ShortcutsXml>("generate${v.name.replaceFirstChar { it.uppercase() }}Shortcuts") {
            appId.set(v.applicationId)
        }
        v.sources.res?.addGeneratedSourceDirectory(t, ShortcutsXml::outDir)
    }
}
